"""FileLineChecker against real curl, in the real image, with networking off.

Needs Docker and the image:  docker build -t triage0-sandbox:dev - < Dockerfile.sandbox
Also needs internet (it clones curl):  TRIAGE0_NETWORK_TESTS=1

The anchors were read from the real source at curl-8_13_0, not from memory:

    lib/dynbuf.c:180  CURLcode Curl_dyn_add(struct dynbuf *s, const char *str)
    lib/dynbuf.c:182    size_t n;                 (two leading spaces)
    lib/dynbuf.c      298 lines, so line 9999 is out of range
    lib/curl_config.h is generated by configure and is not in git
"""

from __future__ import annotations

import os

import pytest

from triage0.checkers.file_line_checker import FileLineChecker
from triage0.core.evidence import EvidenceStatus, MissingEvidence
from triage0.core.models import FileLineClaim
from triage0.sandbox.manager import Session

from ..sandbox.providers.test_docker_local import IMAGE, _image_available

pytestmark = [
    pytest.mark.skipif(not _image_available(), reason=f"docker or {IMAGE} not available"),
    pytest.mark.skipif(
        os.environ.get("TRIAGE0_NETWORK_TESTS") != "1",
        reason="set TRIAGE0_NETWORK_TESTS=1 (clones curl)",
    ),
]


def _claim(
    path: str,
    start: int,
    *,
    end: int | None = None,
    snippet: str | None = None,
) -> FileLineClaim:
    return FileLineClaim(
        claim_id="curl",
        statement="the report cites these lines",
        path=path,
        line_start=start,
        line_end=end,
        expected_snippet=snippet,
    )


def test_a_real_line_is_confirmed(session_curl_8_13_0: Session) -> None:
    result = FileLineChecker().check(
        _claim(
            "lib/dynbuf.c",
            180,
            snippet="CURLcode Curl_dyn_add(struct dynbuf *s, const char *str)",
        ),
        session_curl_8_13_0,
    )

    assert result.status is EvidenceStatus.CONFIRMED
    assert result.proof is not None
    assert result.proof.argv == ("sed", "-n", "180,180p", "--", "/src/lib/dynbuf.c")
    assert result.proof.exit_code == 0
    assert not result.proof.truncated
    assert "CURLcode Curl_dyn_add" in (result.proof.stdout or "")
    assert "lib/dynbuf.c:180-180" in (result.summary or "")


def test_an_indented_snippet_survives_the_model_trim(
    session_curl_8_13_0: Session,
) -> None:
    """The model strips the snippet's outer whitespace; line 182 keeps its own."""

    result = FileLineChecker().check(
        _claim("lib/dynbuf.c", 182, snippet="\t  size_t n;  "),
        session_curl_8_13_0,
    )

    assert result.status is EvidenceStatus.CONFIRMED
    assert result.proof is not None
    assert "  size_t n;" in (result.proof.stdout or "")


def test_a_real_range_is_confirmed(session_curl_8_13_0: Session) -> None:
    result = FileLineChecker().check(
        _claim(
            "lib/dynbuf.c",
            180,
            end=183,
            snippet=(
                "CURLcode Curl_dyn_add(struct dynbuf *s, const char *str)\n"
                "{\n"
                "  size_t n;\n"
                "  DEBUGASSERT(str);"
            ),
        ),
        session_curl_8_13_0,
    )

    assert result.status is EvidenceStatus.CONFIRMED
    assert result.proof is not None
    assert "180,183p" in result.proof.argv
    assert result.proof.argv[-1] == "/src/lib/dynbuf.c"


def test_a_wrong_snippet_is_content_differs(session_curl_8_13_0: Session) -> None:
    result = FileLineChecker().check(
        _claim(
            "lib/dynbuf.c",
            180,
            snippet="CURLcode Curl_dyn_remove(struct dynbuf *s)",
        ),
        session_curl_8_13_0,
    )

    assert result.status is EvidenceStatus.CANT_CHECK
    assert result.missing is MissingEvidence.CONTENT_DIFFERS
    assert "Curl_dyn_add" in (result.summary or "")


def test_a_generated_file_is_absent(session_curl_8_13_0: Session) -> None:
    """lib/curl_config.h is created by configure and is not in git."""

    result = FileLineChecker().check(
        _claim("lib/curl_config.h", 1), session_curl_8_13_0
    )

    assert result.status is EvidenceStatus.CANT_CHECK
    assert result.missing is MissingEvidence.FILE_ABSENT


def test_a_directory_is_not_reported_as_a_missing_file(
    session_curl_8_13_0: Session,
) -> None:
    """sed fails the same way for a directory, but it is present.

    Calling it absent would send a later history check looking for a rename
    that cannot exist.
    """

    result = FileLineChecker().check(_claim("lib", 1), session_curl_8_13_0)

    assert result.status is EvidenceStatus.CANT_CHECK
    assert result.missing is None
    assert "sed exited" in (result.summary or "")


def test_a_line_past_the_end_is_out_of_range(session_curl_8_13_0: Session) -> None:
    result = FileLineChecker().check(
        _claim("lib/dynbuf.c", 9999), session_curl_8_13_0
    )

    assert result.status is EvidenceStatus.CANT_CHECK
    assert result.missing is MissingEvidence.LINE_OUT_OF_RANGE


def test_a_range_without_a_snippet_confirms_the_lines(
    session_curl_8_13_0: Session,
) -> None:
    result = FileLineChecker().check(
        _claim("lib/dynbuf.c", 180, end=183), session_curl_8_13_0
    )

    assert result.status is EvidenceStatus.CONFIRMED
    assert "exists" in (result.summary or "")
